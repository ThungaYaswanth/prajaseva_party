    // Helper to get localized story field
    function getStoryField(story, field, lang) {
      if (!story) return '';
      lang = lang || getCurrentLang();
      return story[field + '_' + lang] || story[field + '_te'] || story[field] || '';
    }

    function getCurrentLang() {
      return localStorage.getItem('prajaseva_lang') || document.documentElement.lang || 'te';
    }

    // Active state tracking
    let currentShowcaseStoryKey = 'featured';
    let currentModalStoryKey = null;

    // 1. Change Main News when a Right-Side Card is clicked
    function selectShowcaseStory(storyKey) {
      const story = STORIES_DB[storyKey];
      if (!story) return;

      currentShowcaseStoryKey = storyKey;
      const lang = getCurrentLang();

      // Automatically collapse any previously expanded full article
      const fullArticleEl = document.getElementById("featuredFullArticle");
      const readMoreBtn = document.getElementById("featuredReadMoreBtn");
      if (fullArticleEl) fullArticleEl.style.display = "none";
      if (readMoreBtn) readMoreBtn.style.display = "inline-flex";

      // Mark the active right-side card
      document.querySelectorAll(".compact-news-card").forEach(card => {
        if (card.getAttribute("data-story-key") === storyKey) {
          card.classList.add("is-active-story");
        } else {
          card.classList.remove("is-active-story");
        }
      });

      // Trigger smooth crossfade transition on the left card
      const leftCard = document.getElementById("featuredBreakingCard");
      if (leftCard) {
        leftCard.classList.remove("is-animating");
        void leftCard.offsetWidth; // Force DOM reflow
        leftCard.classList.add("is-animating");
      }

      // Update image, badge, date, location, title, and description
      const heroImg = document.getElementById("featuredHeroImg");
      const badgeText = document.getElementById("featuredBadgeText");
      const dateEl = document.getElementById("featuredDate");
      const locEl = document.getElementById("featuredLoc");
      const titleEl = document.getElementById("featuredTitle");
      const descEl = document.getElementById("featuredDesc");

      const titleText = getStoryField(story, 'title', lang);

      if (heroImg) {
        heroImg.src = story.img;
        heroImg.alt = titleText;
      }
      if (badgeText) badgeText.textContent = getStoryField(story, 'badge', lang);
      if (dateEl) dateEl.textContent = getStoryField(story, 'date', lang);
      if (locEl) locEl.textContent = getStoryField(story, 'loc', lang);
      if (titleEl) titleEl.textContent = titleText;
      if (descEl) descEl.textContent = getStoryField(story, 'desc', lang);

      // When reading and clicking another card, smoothly scroll back to top of main card
      if (leftCard) {
        const rect = leftCard.getBoundingClientRect();
        if (rect.top < 90 || rect.bottom < window.innerHeight) {
          const targetY = window.pageYOffset + rect.top - 100;
          window.scrollTo({
            top: Math.max(0, targetY),
            behavior: 'smooth'
          });
        }
      }
    }

    // 2. Expand Full Article Inline (Language-aware)
    function expandShowcaseArticle() {
      const story = STORIES_DB[currentShowcaseStoryKey] || STORIES_DB.featured;
      const fullArticleEl = document.getElementById("featuredFullArticle");
      const articleContentEl = document.getElementById("featuredArticleContent");
      const readMoreBtn = document.getElementById("featuredReadMoreBtn");

      if (!fullArticleEl || !articleContentEl) return;

      const lang = getCurrentLang();
      const paras = story['fullArticle_' + lang] || story.fullArticle_te || [];

      let html = '';
      if (Array.isArray(paras) && paras.length > 0) {
        paras.forEach(para => {
          html += `<p>${para}</p>`;
        });
      } else {
        const fallbackDesc = getStoryField(story, 'desc', lang);
        const fallbackNote = lang === 'en'
          ? "Praja Seva Party will soon release a detailed policy action blueprint on this subject. People's welfare is our ultimate purpose."
          : "ఈ అంశంపై ప్రజా సేవ పార్టీ సమగ్ర కార్యాచరణ ప్రణాళికను త్వరలోనే ప్రజల ముందుకు తేనుంది. ప్రజా సంక్షేమమే మా ఏకైక లక్ష్యం.";
        html = `<p>${fallbackDesc}</p><p>${fallbackNote}</p>`;
      }
      articleContentEl.innerHTML = html;

      // Expand downward inline
      fullArticleEl.style.display = "block";
      if (readMoreBtn) readMoreBtn.style.display = "none";
    }

    // 3. Show Less: Collapse Article and scroll to start
    function collapseShowcaseArticle() {
      const fullArticleEl = document.getElementById("featuredFullArticle");
      const readMoreBtn = document.getElementById("featuredReadMoreBtn");

      if (fullArticleEl) fullArticleEl.style.display = "none";
      if (readMoreBtn) readMoreBtn.style.display = "inline-flex";

      const leftCard = document.getElementById("featuredBreakingCard");
      if (leftCard) {
        const rect = leftCard.getBoundingClientRect();
        if (rect.top < 90) {
          const targetY = window.pageYOffset + rect.top - 100;
          window.scrollTo({
            top: Math.max(0, targetY),
            behavior: 'smooth'
          });
        }
      }
    }

    // Helper to populate modal with given story and language
    function populateStoryModal(storyKey, lang) {
      const story = STORIES_DB[storyKey];
      if (!story) return;

      lang = lang || getCurrentLang();
      const title = getStoryField(story, 'title', lang);
      const desc = getStoryField(story, 'desc', lang);
      const badge = getStoryField(story, 'badge', lang);
      const date = getStoryField(story, 'date', lang);
      const loc = getStoryField(story, 'loc', lang);

      const modalBadge = document.getElementById("modalBadge");
      const modalTitle = document.getElementById("modalTitle");
      const modalDate = document.getElementById("modalDate");
      const modalLoc = document.getElementById("modalLoc");
      const modalDesc = document.getElementById("modalDesc");
      const modalImg = document.getElementById("modalImg");

      if (modalBadge) modalBadge.textContent = badge;
      if (modalTitle) modalTitle.textContent = title;
      if (modalDate) modalDate.innerHTML = `<i class="bi bi-calendar3 text-danger"></i> ${date}`;
      if (modalLoc) modalLoc.innerHTML = `<i class="bi bi-geo-alt-fill text-danger"></i> ${loc}`;
      if (modalDesc) modalDesc.textContent = desc;
      if (modalImg) {
        modalImg.src = story.img;
        modalImg.alt = title;
      }
    }

    // Modal popup for latest news cards and upcoming events only
    function openStoryModal(storyKey) {
      currentModalStoryKey = storyKey;
      populateStoryModal(storyKey, getCurrentLang());

      const modalEl = document.getElementById("newsDetailModal");
      if (modalEl) {
        const modal = bootstrap.Modal.getOrCreateInstance(modalEl);
        modal.show();
      }
    }

    function shareArticle() {
      const lang = getCurrentLang();
      const titleEl = document.getElementById("modalTitle");
      const descEl = document.getElementById("modalDesc");
      const shareTitle = titleEl ? titleEl.textContent : document.title;
      const shareDesc = descEl ? descEl.textContent.substring(0, 100) + '...' : '';

      if (navigator.share) {
        navigator.share({
          title: shareTitle,
          text: shareDesc,
          url: window.location.href
        }).catch(() => {});
      } else {
        navigator.clipboard.writeText(window.location.href);
        const alertMsg = (typeof translations !== 'undefined' && translations[lang] && translations[lang].newsCopiedAlert)
          ? translations[lang].newsCopiedAlert
          : (lang === 'en' ? "Link copied to clipboard!" : "లింక్ కాపీ చేయబడింది!");
        alert(alertMsg);
      }
    }

